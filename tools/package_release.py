#!/usr/bin/env python3
"""Export an allowlisted, relocatable source tree and ZIP; never copy .git."""
import hashlib
import json
import os
import shutil
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAME = 'smart-community'
DESTINATION = ROOT / 'release' / NAME
MARKER = '.community_source_export'
PACKAGES = ('smart_community_sim', 'jie_ware', 'my_local_planner')
EXCLUDED_DIRS = {'.git', '__pycache__', 'validation', 'build', 'devel', 'install', '.venv', '.vscode', '.idea'}
ROOT_FILES = ('README.md', 'THIRD_PARTY_NOTICES.md', '.gitignore', '.gitattributes', 'AGENTS.md')


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def selected_files():
    for name in ROOT_FILES:
        yield ROOT / name
    for directory in (*PACKAGES, 'tools', 'docs'):
        for parent, dirs, files in os.walk(str(ROOT / directory), followlinks=False):
            dirs[:] = sorted(name for name in dirs if name not in EXCLUDED_DIRS)
            for name in sorted(files):
                path = Path(parent) / name
                if path.is_symlink():
                    raise RuntimeError('Resolve symlinks before release: ' + str(path.relative_to(ROOT)))
                if (name.endswith(('.pyc', '.pyo', '.so', '.o', '.bag', '.pbstream', '.community_results'))
                        or name == 'my_planner copy.cpp'):
                    continue
                yield path
    # Learning notes remain useful; bulky original documents/evidence stay local.
    yield from sorted((ROOT / 'doc').glob('*.md'))


def main():
    if DESTINATION.is_symlink() or DESTINATION.parent.is_symlink():
        raise RuntimeError('Export destination must not be a symlink')
    DESTINATION.parent.mkdir(parents=True, exist_ok=True)
    # Export lives under workspace/src: keep catkin from scanning package copies.
    # This marker belongs to release/, not the exported repository or ZIP.
    (DESTINATION.parent / 'CATKIN_IGNORE').touch()
    if DESTINATION.exists():
        if (DESTINATION / '.git').exists():
            raise RuntimeError('Export contains Git history; move it to a separate development directory first: ' + str(DESTINATION))
        if not (DESTINATION / MARKER).is_file():
            raise RuntimeError('Refusing to overwrite an unowned export directory: ' + str(DESTINATION))
        shutil.rmtree(str(DESTINATION))
    DESTINATION.mkdir(parents=True)
    (DESTINATION / MARKER).write_text('Generated by tools/package_release.py; safe to regenerate.\n')
    manifest = {'format': 1, 'name': NAME, 'ros': 'noetic', 'ubuntu': '20.04', 'files': []}
    for source in selected_files():
        relative = source.relative_to(ROOT)
        target = DESTINATION / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(str(source), str(target))
        # Model weights are data even if the original file had mode 777.
        executable = target.suffix in ('.sh', '.py') and target.read_bytes().startswith(b'#!')
        target.chmod(0o755 if executable else 0o644)
        manifest['files'].append({'path': relative.as_posix(), 'bytes': target.stat().st_size, 'sha256': sha256(target)})
    (DESTINATION / 'release_manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
    archive = DESTINATION.parent / (NAME + '-github.zip')
    with zipfile.ZipFile(str(archive), 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=6) as output:
        for path in sorted(DESTINATION.rglob('*')):
            if path.is_file() and path.name != MARKER:
                output.write(str(path), str(path.relative_to(DESTINATION.parent)))
    digest_file = archive.with_suffix(archive.suffix + '.sha256')
    digest_file.write_text('{}  {}\n'.format(sha256(archive), archive.name))
    print('Source directory: ' + str(DESTINATION))
    print('ZIP: {} ({:.1f} MiB; {} source files)'.format(archive, archive.stat().st_size / 1024 ** 2, len(manifest['files'])))
    print('SHA256: ' + str(digest_file))


if __name__ == '__main__':
    main()
